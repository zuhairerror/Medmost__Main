-- 1. Ensure consultations table exists
CREATE TABLE IF NOT EXISTS public.consultations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  country TEXT NOT NULL,
  message TEXT
);

-- 2. Add user_id column if not already present (links authenticated patient to their consultation)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'consultations' 
      AND column_name = 'user_id'
  ) THEN
    ALTER TABLE public.consultations ADD COLUMN user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL;
  END IF;
END $$;

-- Create index on user_id and email for fast consultation queries
CREATE INDEX IF NOT EXISTS idx_consultations_user_id ON public.consultations(user_id);
CREATE INDEX IF NOT EXISTS idx_consultations_email ON public.consultations(email);

-- 3. Keep Row Level Security (RLS) ENABLED to protect patient confidentiality
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;

-- 4. Clean up any previous conflicting policies
DROP POLICY IF EXISTS "Allow anonymous patient inserts" ON public.consultations;
DROP POLICY IF EXISTS "Allow anonymous patient consultation submissions" ON public.consultations;
DROP POLICY IF EXISTS "Allow public consultation submissions" ON public.consultations;
DROP POLICY IF EXISTS "Allow authenticated staff to view consultations" ON public.consultations;
DROP POLICY IF EXISTS "Allow coordinators to view consultations" ON public.consultations;
DROP POLICY IF EXISTS "Allow staff to view consultations" ON public.consultations;
DROP POLICY IF EXISTS "Allow users to view own consultations" ON public.consultations;
DROP POLICY IF EXISTS "Users can view own consultations" ON public.consultations;

-- 5. NARROWLY SCOPED INSERT POLICY for public / anonymous / authenticated patients
-- Only allows INSERT with validation. Strictly preserves existing working consultation form.
CREATE POLICY "Allow anonymous patient consultation submissions" 
ON public.consultations 
FOR INSERT 
TO anon, authenticated
WITH CHECK (
  length(trim(name)) > 0 AND 
  length(trim(phone)) > 0
);

-- 6. STRICT PRIVATE SELECT POLICY for patient dashboard
-- Authenticated users can ONLY view their OWN consultation records.
-- Matches by either their user_id OR their verified login email.
-- Under NO circumstances can any patient see another patient's consultations.
CREATE POLICY "Users can view own consultations" 
ON public.consultations 
FOR SELECT 
TO authenticated
USING (
  (user_id IS NOT NULL AND user_id = auth.uid()) OR
  (lower(trim(email)) = lower(trim(auth.jwt() ->> 'email')))
);

-- 7. User Profiles Table (Linked to Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT,
  phone TEXT,
  country TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Profile RLS Policies: users manage only their own profile
DROP POLICY IF EXISTS "Users can view own profile" ON public.profiles;
CREATE POLICY "Users can view own profile" 
ON public.profiles 
FOR SELECT 
TO authenticated 
USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile" 
ON public.profiles 
FOR UPDATE 
TO authenticated 
USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can insert own profile" ON public.profiles;
CREATE POLICY "Users can insert own profile" 
ON public.profiles 
FOR INSERT 
TO authenticated 
WITH CHECK (auth.uid() = id);

-- 8. Auto-create or sync profile on new user signup trigger
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, created_at, updated_at)
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'full_name', ''),
    NOW(),
    NOW()
  )
  ON CONFLICT (id) DO UPDATE
  SET full_name = EXCLUDED.full_name,
      updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 9. Grant appropriate privileges to Postgres roles
GRANT INSERT ON TABLE public.consultations TO anon, authenticated;
GRANT SELECT ON TABLE public.consultations TO authenticated;
GRANT ALL ON TABLE public.consultations TO service_role;
GRANT ALL ON TABLE public.profiles TO authenticated;
GRANT ALL ON TABLE public.profiles TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 10. Notify PostgREST to reload schema cache
NOTIFY pgrst, 'reload schema';
